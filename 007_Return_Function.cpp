/*
◆──────────────────────────◆
07. Return Function
◆──────────────────────────◆

💡 Remember
Return sends a value
back to the caller.

*/

#include <iostream>
using namespace std;

// Function Definition
int add(int a, int b)
{
    return a + b;
}

// Main Function
int main()
{
    // Function Call
    cout << add(2, 3);

    return 0;
}

/*
Output:
5
*/
