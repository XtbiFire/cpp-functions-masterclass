/*
◆──────────────────────────◆
      65. Returning Char
◆──────────────────────────◆

💡 Remember

A char function returns
a single character value.

Character values are written
inside single quotes (' ').

*/

#include <iostream>
using namespace std;

// Function
char getGrade()
{
    return 'A';
}

// Main Function
int main()
{
    cout << "Grade : " << getGrade();

    return 0;
}

/*

Output

Grade : A

*/
