/*
◆──────────────────────────◆
09. Ignore Return Value
◆──────────────────────────◆

💡 Remember
A function can return a value,
but you may choose to ignore it.

*/

#include <iostream>
using namespace std;

// Function Definition
int show()
{
    return 5;
}

// Main Function
int main()
{
    // Function Call
    show();

    return 0;
}

/*
Output:
No Output
*/
