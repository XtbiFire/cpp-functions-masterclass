/*
◆──────────────────────────◆
01. Function Definition And Call
◆──────────────────────────◆

💡 Remember
Define the function first,
then call it from main().

*/

#include <iostream>
using namespace std;

// Function Definition
void hello()
{
    cout << "Hello";
}

// Main Function
int main()
{
    // Function Call
    hello();

    return 0;
}

/*
Output:
Hello
*/
